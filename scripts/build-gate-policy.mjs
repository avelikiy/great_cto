#!/usr/bin/env node
// Ship the CLI's gate policy as dependency-free plugin runtime. The TypeScript
// source remains authoritative; --check refuses a stale generated copy.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = fs.readFileSync(path.join(root, 'packages/cli/src/archetypes.ts'), 'utf8').replace(/\r\n/g, '\n');
const start = source.indexOf('export const GATES_BY_ARCHETYPE:');
const end = source.indexOf('/**\n * Returns the ordered list of reviewers', start);
if (start < 0 || end <= start) throw Error('Cannot locate the canonical gate-policy section');
const require = createRequire(path.join(root, 'packages/cli/package.json'));
const ts = require('typescript');
const compiled = ts.transpileModule(source.slice(start, end), {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022,
    newLine: ts.NewLineKind.LineFeed, removeComments: false },
}).outputText;
const output = '// Generated by scripts/build-gate-policy.mjs from packages/cli/src/archetypes.ts.\n'
  + '// Do not edit; regenerate, then run --check. No CLI build is needed at runtime.\n' + compiled;
const target = path.join(root, 'scripts/lib/gate-policy.mjs');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) {
    console.error('gate-policy is stale: run node scripts/build-gate-policy.mjs');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(target, output);
  console.log('Generated scripts/lib/gate-policy.mjs');
}
