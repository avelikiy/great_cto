#!/usr/bin/env node
// Write packages/board/openapi.json: every /api route of the board, its methods,
// and — for every route that can be read — the status and the response shape a
// fresh board on a throwaway project answers. packages/board/openapi-contract.test.mjs
// then holds the live board to it, so a response that loses a key, changes a type
// or starts failing is a red test, not a broken screen.
//
// The shapes are observed, not designed: rerun after a deliberate API change and
// review the diff like code. Summaries written by hand survive a rerun.
//
//   node scripts/board-openapi.mjs            print what would change
//   node scripts/board-openapi.mjs --write    rewrite the contract
import fs from 'node:fs';
import { routeInventory } from '../tests/helpers/board-routes.mjs';
import { CONTRACT, startContractBoard, call, inferSchema, contractPath, probePath } from '../tests/helpers/board-contract.mjs';

const write = process.argv.includes('--write');
const old = fs.existsSync(CONTRACT) ? JSON.parse(fs.readFileSync(CONTRACT, 'utf8')) : { paths: {} };
const version = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version;

const board = await startContractBoard();
const paths = {};
try {
  for (const r of routeInventory()) {
    const key = contractPath(r);
    const was = old.paths?.[key] || {};
    const entry = {};
    const methods = r.methods.includes('ANY') ? ['get', 'post'] : r.methods.map((m) => m.toLowerCase());
    for (const m of methods) {
      const op = { summary: was[m]?.summary || '', 'x-methods-declared': r.methods.includes('ANY') ? 'any' : 'explicit' };
      if (m === 'get') {
        const res = await call(board.port, probePath(r));
        op['x-probe'] = probePath(r);
        const content = res.type.includes('event-stream') ? { 'text/event-stream': {} }
          : res.json !== undefined ? { 'application/json': { schema: inferSchema(res.json) } }
            : { [res.type.split(';')[0] || 'text/plain']: {} };
        op.responses = { [String(res.status)]: { description: was.get?.responses?.[res.status]?.description || 'observed on a fresh project', content } };
      } else {
        op.responses = { default: { description: 'not probed: a write needs a request body the contract does not invent' } };
      }
      entry[m] = op;
    }
    paths[key] = entry;
  }
} finally {
  await board.close();
}

const doc = {
  openapi: '3.1.0',
  info: {
    title: 'great_cto board API',
    version,
    description: 'Local board API (127.0.0.1). Generated by scripts/board-openapi.mjs from a fresh board; checked by packages/board/openapi-contract.test.mjs.',
  },
  paths,
};
const next = JSON.stringify(doc, null, 2) + '\n';
const prev = fs.existsSync(CONTRACT) ? fs.readFileSync(CONTRACT, 'utf8') : '';
const strip = (s) => s.replace(/"version": "[^"]*"/, '');
if (strip(prev) === strip(next)) { console.log(`contract unchanged: ${Object.keys(paths).length} routes`); process.exit(0); }
if (write) { fs.writeFileSync(CONTRACT, next); console.log(`wrote ${CONTRACT}: ${Object.keys(paths).length} routes`); }
else { console.log(`contract would change (${Object.keys(paths).length} routes); rerun with --write and review the diff`); process.exit(1); }
