/**
 * Write the fixture project into `dir`. Idempotent: the same input every time,
 * so two captures of an unchanged UI differ only in the pixels the UI changed.
 * @returns {string} the project root that was written
 */
export function buildFixture(dir) {
  const gc = path.join(dir, '.great_cto');
  fs.mkdirSync(path.join(gc, 'verdicts'), { recursive: true });
  fs.mkdirSync(path.join(gc, 'logs'), { recursive: true });

  fs.writeFileSync(path.join(gc, 'PROJECT.md'), PROJECT_MD);
  fs.writeFileSync(path.join(gc, 'tasks.md'), TASKS_MD);
  fs.writeFileSync(path.join(gc, 'brain.md'),
    '# Patterns in use\n\n- Every write to the payment provider carries an idempotency key.\n'
    + '- Totals are computed once, server-side, and never recomputed in the client.\n');
  fs.writeFileSync(path.join(gc, 'lessons.md'),
    '# Lessons\n\n- A retry without an idempotency key is not a retry, it is a second charge.\n');
  fs.writeFileSync(path.join(gc, 'cost-history.log'), COST_LOG);

  for (const [agent, verdict, feature, hoursAgo, note] of VERDICTS) {
    fs.writeFileSync(path.join(gc, 'verdicts', `${agent}-${feature}.md`),
      `---\nagent: ${agent}\nverdict: ${verdict}\nfeature: ${feature}\ndate: ${at(hoursAgo)}\n---\n\n${note}\n`);
  }

  fs.writeFileSync(path.join(gc, 'logs', 'session-2026-08-19.md'),
    `# Session — checkout hardening\n\nWhat was done:\n- Idempotency keys on payment intents\n`
    + `- Webhook signature verification\n\nLeft pending:\n- Partial-refund totals (acme-2b)\n`);

  // A real project shape. `great-cto ci` detects the archetype from the code, and
  // an empty directory detects as greenfield — a fixture that fails the product's
  // own check is a fixture that cannot demonstrate it.
  fs.writeFileSync(path.join(dir, 'package.json'), JSON.stringify({
    name: 'acme-storefront', version: '0.4.0', private: true, type: 'module',
    scripts: { dev: 'next dev', build: 'next build', test: 'vitest run' },
    dependencies: { next: '^15.0.0', react: '^19.0.0', 'react-dom': '^19.0.0', stripe: '^17.0.0' },
    devDependencies: { typescript: '^5.6.0', vitest: '^2.0.0' },
  }, null, 2) + '\n');
  fs.mkdirSync(path.join(dir, 'src', 'app'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'src', 'app', 'page.tsx'),
    'export default function Storefront() {\n  return <main>ACME</main>;\n}\n');
  fs.writeFileSync(path.join(dir, 'src', 'checkout.ts'),
    '/** Every payment intent carries an idempotency key. */\n'
    + 'export async function createIntent(cartId: string, key: string) {\n'
    + '  return { cartId, idempotencyKey: key };\n}\n');
  fs.writeFileSync(path.join(dir, 'tsconfig.json'),
    JSON.stringify({ compilerOptions: { strict: true, module: 'esnext', target: 'es2022' } }, null, 2) + '\n');

  // A README so the Docs screen has something of its own to list.
  fs.writeFileSync(path.join(dir, 'README.md'),
    '# acme-storefront\n\nA sample commerce project used to photograph the great_cto board.\n');
  fs.mkdirSync(path.join(dir, 'docs'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'docs', 'ARCHITECTURE.md'),
    '# Architecture\n\nNext.js storefront, Postgres, a payment provider held at arm\'s length.\n'
    + 'See [the checkout decision](decisions/ADR-001-checkout.md).\n');
  fs.mkdirSync(path.join(dir, 'docs', 'decisions'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'docs', 'decisions', 'ADR-001-checkout.md'),
    '# ADR-001 — Checkout stays off our origin\n\n**Status:** Accepted\n\n'
    + 'Card data never reaches our servers, which keeps us in PCI SAQ-A.\n');

  return dir;
}

